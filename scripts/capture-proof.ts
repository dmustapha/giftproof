// File: scripts/capture-proof.ts
// Judge proof artifact generator (PRD §7.6). Runs ONE real journey through the orchestrator and
// writes submission/proof.md: the redacted /v2/insights request (X-Api-Key: [REDACTED]), the
// resolved entity IDs per seed, the Qloo API call count for the journey, ONE raw explainability
// block (real contributors, never a fabricated score), and coverage stats. Everything here is
// recomputable from committed data by scripts/verify-claims.ts (INVARIANTS VERIFY-BEFORE-CLAIMING).
//
//   cd giftproof-app && npx tsx --env-file=.env.local scripts/capture-proof.ts
import { writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join } from "node:path";
import { runGift } from "../src/lib/orchestrate";
import type { GiftResponse } from "../src/lib/types";

const SENTENCE = "My sister is obsessed with Succession, Aesop skincare, and A24 films.";
const ROOT = join(import.meta.dirname, "..");

function redactedInsightsRequest(r: GiftResponse): string {
  const entityIds = r.seeds.filter((s) => s.signal.kind === "entity").map((s) => s.signal.value);
  const tagIds = r.seeds.filter((s) => s.signal.kind === "tag").map((s) => s.signal.value);
  const params = new URLSearchParams({
    "filter.type": r.domain,
    "feature.explainability": "true",
    "filter.popularity.min": "0.3",
    "bias.content_based": "0.35",
    "diversify.by": "subtype",
    take: "12",
  });
  if (entityIds.length) params.set("signal.interests.entities", entityIds.join(","));
  if (tagIds.length) params.set("signal.interests.tags", tagIds.join(","));
  return `GET https://hackathon.api.qloo.com/v2/insights?${params.toString()}\nX-Api-Key: [REDACTED]`;
}

async function main() {
  const r = await runGift(SENTENCE);
  if (r.picks.length === 0) {
    console.error(`capture-proof: journey produced no picks (degraded=${r.degraded}).`);
    process.exit(1);
  }

  const callCount = r.coverage.resolved + 1; // /search per resolved seed + 1 insights call
  const firstWithExplain = r.picks.find((p) => p.pick.explain.length > 0) ?? r.picks[0];

  const md = `# GiftProof — Qloo Integration Proof

> Generated by \`scripts/capture-proof.ts\` from one REAL journey. Every number here is recomputable
> from \`data/seed-journeys.json\` by \`scripts/verify-claims.ts\` (it refuses read-back).

## Journey
Sentence: "${SENTENCE}"

## Redacted request (the cross-domain /v2/insights call — the differentiator)
\`\`\`
${redactedInsightsRequest(r)}
\`\`\`

## Resolved entity IDs (seed tastes -> real Qloo entities/tags)
${r.seeds.map((s) => `- ${s.label}: \`${s.signal.value}\` (${s.signal.kind}, via /${s.signal.source})`).join("\n")}

## Coverage
${r.coverage.resolved} of ${r.coverage.total} tastes resolved to real Qloo signals.

## Qloo API call count (this journey)
${callCount} calls = ${r.coverage.resolved}x /search + 1x /v2/insights.

## Ranked picks (${r.picks.length}, Qloo-ordered — the LLM never ranks)
${r.picks.slice(0, 5).map((p, i) => `${i + 1}. ${p.pick.name} (affinity ${p.pick.affinity?.toFixed(3) ?? "rank-band " + p.pick.rankBand}) -> gift: ${p.gift?.title ?? "NO_GIFT_MATCH"}`).join("\n")}

## Raw explainability block for one pick (real contributors, never a fabricated score)
Pick: ${firstWithExplain.pick.name}
\`\`\`json
${JSON.stringify(firstWithExplain.pick.explain, null, 2)}
\`\`\`
This is the "we chose because fans of X also like Y" evidence that a generic LLM cannot reproduce:
it comes from Qloo's aggregate behavioral affinity graph, not from the model's guess.

## What this proves
Qloo's cross-domain \`/v2/insights\` + \`feature.explainability\` do the irreplaceable ranking work.
Delete the Qloo call and the picks are empty (NN-1 kill-test) — the product dies without Qloo.
`;

  const subDir = join(ROOT, "submission");
  if (!existsSync(subDir)) mkdirSync(subDir, { recursive: true });
  const path = join(subDir, "proof.md");
  writeFileSync(path, md);
  console.log(`wrote proof artifact to ${path} (call count: ${callCount}, picks: ${r.picks.length})`);
}

main().catch((e) => { console.error("capture-proof failed:", e); process.exit(1); });
